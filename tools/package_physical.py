"""Package only a source-matched, timing-accepted common image and real evidence."""
from pathlib import Path
import argparse,datetime,hashlib,json,zipfile
try:
    from .report_paths import resolve_report_path
except ImportError:
    from report_paths import resolve_report_path
ROOT=Path(__file__).resolve().parents[1]

def digest(path):return hashlib.sha256(path.read_bytes()).hexdigest()

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--validation',type=Path,default=ROOT/'build/validation/physical')
    parser.add_argument('--hardware',type=Path,help='Optional accepted hardware evidence directory, including an archived reports path')
    parser.add_argument('--output-dir',type=Path,default=ROOT/'build/delivery/physical')
    args=parser.parse_args()
    out=args.output_dir.resolve()
    if not out.is_relative_to((ROOT/'build').resolve()):parser.error('--output-dir must be under build/; historical deliveries are immutable')
    build=ROOT/'build/physical_runtime';validation=resolve_report_path(args.validation.resolve())
    execution=json.loads((build/'execution.json').read_text());tests=json.loads((validation/'validation.json').read_text())
    if execution.get('status')!='passed' or tests.get('status')!='passed':raise RuntimeError('Accepted implementation and tests required')
    manifest=(build/'build_manifest.txt').read_text()
    if 'schema=physical_v3' not in manifest or 'status=implemented_timing_pass_bitstream_generated' not in manifest:raise RuntimeError('Wrong/unaccepted firmware manifest')
    for source in (build/'source_sha256.json',validation/'source_sha256.json'):
        for name,expected in json.loads(source.read_text()).items():
            if digest(ROOT/name)!=expected:raise RuntimeError('Evidence source changed: '+name)
    accepted=json.loads((build/'artifacts_sha256.json').read_text())
    for name in ('obsidian_benchmark.bit','obsidian_benchmark.ltx'):
        if accepted.get(name)!=digest(build/name):raise RuntimeError('Artifact hash mismatch: '+name)
    hardware_directory=resolve_report_path(args.hardware.resolve()) if args.hardware else ROOT/'build/report_outputs/hardware_validation'
    hardware_path=hardware_directory/'verification.json'
    hardware=json.loads(hardware_path.read_text(encoding='utf-8')) if hardware_path.exists() else None
    if hardware:
        if hardware.get('source')!='hardware_jtag' or hardware.get('status')!='passed':raise RuntimeError('Hardware evidence not accepted')
        if hardware.get('bitstream_sha256')!=digest(build/'obsidian_benchmark.bit'):raise RuntimeError('Hardware BIT mismatch')
        for name,expected in hardware['input_sha256'].items():
            if digest(resolve_report_path(name))!=expected:raise RuntimeError('Hardware evidence changed: '+name)
    selected=set()
    for folder in ('rtl','constraints','config','scripts','sim','tools','docs','reference','.vscode'):
        for p in (ROOT/folder).rglob('*'):
            if p.is_file() and '__pycache__' not in p.parts and p.suffix.lower() in ('.vhd','.xdc','.json','.py','.tcl','.md','.txt','.bat','.ps1','.sh','.js'):
                selected.add(p)
    for name in ('README.md','LICENSE','Obsidian_RAG.code-workspace','SOURCE_PROVENANCE.json','family.json','family.tcl','.gitignore','.gitattributes'):
        if (ROOT/name).exists():selected.add(ROOT/name)
    for p in validation.iterdir():
        if p.is_file():selected.add(p)
    if hardware:
        for p in hardware_directory.rglob('*'):
            if p.is_file():selected.add(p)
    for p in (ROOT/'reports').rglob('*'):
        if p.is_file():selected.add(p)
    for p in build.iterdir():
        if p.is_file() and p.suffix.lower() in ('.bit','.ltx','.rpt','.json','.txt','.log'):selected.add(p)
    for p in (build/'attempts').rglob('*'):
        if p.is_file() and p.suffix.lower() in ('.rpt','.json','.txt','.log'):selected.add(p)
    hashes={p.relative_to(ROOT).as_posix():digest(p) for p in sorted(selected)}
    delivery=dict(schema='obsidian_physical_delivery_v1',created_at_utc=datetime.datetime.now(datetime.timezone.utc).isoformat(),
        status='implemented_timing_pass_bitstream_generated',top='obsidian_physical_top',physical_boards=3,virtual_nodes=0,
        common_bitstream='build/physical_runtime/obsidian_benchmark.bit',common_probes='build/physical_runtime/obsidian_benchmark.ltx',
        roles={'A':0,'B':1,'C':2},runtime_modes={'CT':1,'RAG':2},max_payload_bytes=4096,max_local_bytes=1365,max_hops=65535,
        rtl_cases=len(tests['rtl_cases']),python_tests=tests['python_tests'],hardware_programmed=bool(hardware),hardware_measurements=hardware['summary_rows'] if hardware else 0,
        hardware_trials=hardware['physical_trials'] if hardware else 0,hardware_evidence=hardware_path.relative_to(ROOT).as_posix() if hardware else None,
        archive_scope='Source project, common BIT/LTX, accepted reports and validation. IP caches/checkpoints are regenerated by the build scripts.',
        historical_profiles='Legacy reports/specifications are retained and do not validate the new image.',files_sha256=hashes)
    out.mkdir(parents=True,exist_ok=True)
    artifact_manifest=out/'ARTIFACT_MANIFEST.json';artifact_manifest.write_text(json.dumps(delivery,indent=2)+'\n',encoding='utf-8')
    selected.add(artifact_manifest);hashes['ARTIFACT_MANIFEST.json']=digest(artifact_manifest)
    sums=out/'SHA256SUMS';sums.write_text(''.join(f'{value}  {name}\n' for name,value in sorted(hashes.items())),encoding='utf-8');selected.add(sums)
    archive=out/'Obsidian_RAG_physical.zip'
    with zipfile.ZipFile(archive,'w',zipfile.ZIP_DEFLATED,compresslevel=6) as z:
        for p in sorted(selected):z.write(p,p.name if p in (artifact_manifest,sums) else p.relative_to(ROOT).as_posix())
    with zipfile.ZipFile(archive) as z:
        if z.testzip() is not None:raise RuntimeError('ZIP CRC verification failed')
    checksum=digest(archive);archive.with_suffix('.zip.sha256').write_text(checksum+'  '+archive.name+'\n')
    print(json.dumps(dict(archive=str(archive),bytes=archive.stat().st_size,sha256=checksum,files=len(selected),hardware_programmed=bool(hardware)),indent=2))
if __name__=='__main__':main()
